    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        try {

            String idProduk = IdProduk.getText();

            int jumlah = Integer.parseInt(
                Jumlahpesan.getText()
            );

            Produk produk
            = DataInitiate.katalogSupplier
            .getProdukById(idProduk);

            if (produk == null) {

                JOptionPane.showMessageDialog(
                    this,
                    "Produk tidak ditemukan"
                );

                return;
            }

            DataInitiate.keranjang.tambahItem(
                produk,
                jumlah
            );

            JOptionPane.showMessageDialog(
                this,
                "Produk berhasil ditambahkan"
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this,
                "Jumlah harus angka"
            );

        } catch (ProdukExpiredException
            | StokTidakCukupException e) {

            JOptionPane.showMessageDialog(
                this,
                e.getMessage()
            );
        }
    }//GEN-LAST:event_jButton1ActionPerformed


