    private void loadStok() {

        StringBuilder sb = new StringBuilder();

        for (Produk p : DataInitiate.katalogSupplier.getSemuaProduk()) {

            sb.append("ID: ")
                    .append(p.getId())
                    .append("\nNama: ")
                    .append(p.getNamaProduk())
                    .append("\nStok: ")
                    .append(p.getStokSaatIni())
                    .append("\nExpired: ")
                    .append(p.getTanggalExpired())
                    .append("\n--------------------------------\n");
        }

        stokToko.setText(sb.toString());
    }

