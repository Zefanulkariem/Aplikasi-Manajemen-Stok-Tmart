    private void loadRiwayat() {

        StringBuilder sb = new StringBuilder();

        if (DataInitiate.karyawan.getDaftarPemesanan().isEmpty()) {

            sb.append("Belum ada pemesanan");

        } else {

            int nomor = 1;

            for (Pemesanan p : DataInitiate.karyawan.getDaftarPemesanan()) {

                sb.append("=== Pemesanan ")
                        .append(nomor)
                        .append(" ===\n");

                sb.append(p.toString())
                        .append("\n\n");

                nomor++;
            }
        }

        isiRiwayat.setText(sb.toString());
    }
    

