    private void loadPemesanan() {

        StringBuilder sb = new StringBuilder();

        var list = DataInitiate.karyawan.getDaftarPemesanan();

        if (list.isEmpty()) {
            sb.append("Belum ada pemesanan");
        } else {

            for (Pemesanan p : list) {
                sb.append("ID: ").append(p.getId())
                        .append(" | Nota: ").append(p.getNomorNota())
                        .append(" | Status: ").append(p.getStatusPemesanan())
                        .append("\n");
            }
        }

        isiPesan.setText(sb.toString());
    }

