    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String id = idproduk.getText();

        Pemesanan target = null;

        for (Pemesanan p : DataInitiate.karyawan.getDaftarPemesanan()) {
            if (p.getId().equals(id)) {
                target = p;
                break;
            }
        }

        if (target == null) {
            JOptionPane.showMessageDialog(this, "Pemesanan tidak ditemukan");
            return;
        }

        // =========================
        // LOGIC SAMA SEPERTI CLI
        // =========================
        for (ItemPemesanan item : target.getItems()) {

            String idProduk = item.getIdProduk();
            int jumlah = item.getJumlahPesan();

            Produk produk = DataInitiate.katalogSupplier.getProdukById(idProduk);

            if (produk != null) {
                produk.updateStok(jumlah);
            }
        }
        target.setStatusPemesanan(StatusPemesanan.DITERIMA);

        JOptionPane.showMessageDialog(this, "Penerimaan berhasil");

        loadPemesanan();
    }//GEN-LAST:event_jButton1ActionPerformed

