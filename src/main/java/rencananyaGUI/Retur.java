    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String id = produkid.getText();

        int jumlah;

        try {
            jumlah = Integer.parseInt(jumlahRetur.getText());
        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Jumlah tidak valid"
            );

            return;
        }

        Produk target
                = DataInitiate.katalogSupplier.getProdukById(id);

        if (target == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Produk tidak ditemukan"
            );

            return;
        }

        if (jumlah > target.getStokSaatIni()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Stok tidak mencukupi"
            );

            return;
        }

        target.updateStok(-jumlah);

        JOptionPane.showMessageDialog(
                this,
                "Retur berhasil"
        );

        loadProduk();
    }//GEN-LAST:event_jButton1ActionPerformed

