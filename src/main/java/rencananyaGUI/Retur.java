    private void loadProduk() {

        StringBuilder sb = new StringBuilder();

        for (Produk p : DataInitiate.katalogSupplier.getSemuaProduk()) {

            sb.append("ID: ")
                    .append(p.getId())
                    .append(" | ")
                    .append(p.getNamaProduk())
                    .append(" | Stok: ")
                    .append(p.getStokSaatIni())
                    .append("\n");
        }

        stoktokoretur.setText(sb.toString());
    }

