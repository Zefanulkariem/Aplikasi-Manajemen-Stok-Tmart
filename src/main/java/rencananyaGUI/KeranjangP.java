    private void loadKeranjang() {

        StringBuilder sb = new StringBuilder();

        if (DataInitiate.keranjang.getItems().isEmpty()) {
            sb.append("Keranjang kosong");
        } else {
            for (ItemKeranjang item : DataInitiate.keranjang.getItems()) {
                sb.append(item.toString()).append("\n");
            }
        }

        isiKeranjang.setText(sb.toString());
    }

