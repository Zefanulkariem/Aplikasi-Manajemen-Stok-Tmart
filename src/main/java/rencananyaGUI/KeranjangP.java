    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
         if (DataInitiate.keranjang.getItems().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Keranjang masih kosong!"
        );

        return;
    }

    String alamat = JOptionPane.showInputDialog(
            this,
            "Masukkan alamat pengiriman:"
    );

    if (alamat == null || alamat.trim().isEmpty()) {
        return;
    }

    try {

        String idPemesanan =
                "S" + String.format(
                        "%03d",
                        DataInitiate.karyawan.getDaftarPemesanan().size() + 1
                );

        String nomorNota =
                "NOTA" + String.format(
                        "%03d",
                        DataInitiate.karyawan.getDaftarPemesanan().size() + 1
                );

        Pemesanan pemesanan = new Pemesanan(
                idPemesanan,
                nomorNota,
                LocalDate.now(),
                alamat
        );

        pemesanan.buatDariKeranjang(
                DataInitiate.keranjang
        );

        pemesanan.cekKetersediaan(
                DataInitiate.katalogSupplier
        );

        DataInitiate.karyawan.tambahPemesanan(
                pemesanan
        );

        DataInitiate.keranjang.kosongkan();

        JOptionPane.showMessageDialog(
                this,
                "Pemesanan berhasil dibuat\n"
                + "Nomor Nota : "
                + pemesanan.getNomorNota()
        );

        loadKeranjang();

    } catch (StokTidakCukupException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton4ActionPerformed


